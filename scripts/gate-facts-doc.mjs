#!/usr/bin/env node
// Writes the gate facts table in docs/WORKFLOWS.md from GATE_FACT_VOCABULARY
// (packages/domain/src/gate-facts.ts), so the docs, the validator and the
// planner prompt read one list (P15).
//
//   node scripts/gate-facts-doc.mjs           # print whether the doc is current
//   node scripts/gate-facts-doc.mjs --write   # rewrite the table
//
// Build first: the vocabulary is read from packages/domain/dist.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = join(root, 'docs', 'WORKFLOWS.md');
export const START = '<!-- gate-facts:start (generated by scripts/gate-facts-doc.mjs from GATE_FACT_VOCABULARY; do not edit by hand) -->';
export const END = '<!-- gate-facts:end -->';

const TYPE = {
  outcome: 'PASS / FAIL / SKIP',
  boolean: 'boolean',
  number: 'number',
  verdict: 'text',
  approval: 'PENDING / APPROVED / REJECTED / EXPIRED / CANCELLED',
};
const SCOPE = { step: 'step', mission: 'whole mission', workspace: 'whole project' };
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderFactsTable(vocabulary) {
  const rows = (scope) => vocabulary.filter((f) => f.scope === scope)
    .map((f) => `| \`${f.name}\` | ${TYPE[f.type] ?? f.type} | ${SCOPE[f.scope]} | ${cell(f.description)} | ${cell(f.measuredIn)} |`);
  const head = ['| Fact | Type | Scope | Meaning | Measured in |', '|---|---|---|---|---|'];
  return [
    START,
    '',
    '#### Facts a step\'s gate can read',
    '',
    ...head,
    ...rows('step'),
    '',
    '#### Facts for the whole mission or project',
    '',
    'These are measured by the daemon for its own rules (the readiness check, the backlog pull, the limit stop, the',
    'stalled row) and for the desk. A workflow or a plan whose gate reads one is refused when it is written, with a',
    'reason such as "The gate on \'release\' reads mission.stalled, which is only known for the whole mission, not',
    'inside a step."',
    '',
    ...head,
    ...rows('mission'),
    ...rows('workspace'),
    '',
    END,
  ].join('\n');
}

export function withTable(doc, table) {
  const start = doc.indexOf(START.slice(0, 22));
  const end = doc.indexOf(END);
  if (start === -1 || end === -1) throw new Error(`${DOC} has no gate-facts markers`);
  return doc.slice(0, start) + table + doc.slice(end + END.length);
}

async function main() {
  const { GATE_FACT_VOCABULARY } = await import(pathToFileURL(join(root, 'packages/domain/dist/index.js')).href);
  const doc = readFileSync(DOC, 'utf8');
  const next = withTable(doc, renderFactsTable(GATE_FACT_VOCABULARY));
  if (process.argv.includes('--write')) {
    writeFileSync(DOC, next);
    console.log(next === doc ? 'docs/WORKFLOWS.md: facts table already current' : 'docs/WORKFLOWS.md: facts table rewritten');
    return;
  }
  if (next !== doc) {
    console.error('docs/WORKFLOWS.md: the facts table differs from GATE_FACT_VOCABULARY. Run: node scripts/gate-facts-doc.mjs --write');
    process.exit(1);
  }
  console.log('docs/WORKFLOWS.md: facts table current');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
